import { afterEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { CommunityProfilePage } from './CommunityProfilePage'
import { readCommunityProfileContent, readCommunityProfileDetails } from '../api'
import { initialProfile } from '../../../mock/data'
Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value: function (this: HTMLDialogElement) { this.setAttribute('open', '') } })
Object.defineProperty(HTMLDialogElement.prototype, 'close', { configurable: true, value: function (this: HTMLDialogElement) { this.removeAttribute('open') } })
afterEach(cleanup)
function props() {
  return { content: readCommunityProfileContent(), profile: readCommunityProfileDetails(initialProfile),
    preferences: { reminders: true, replies: true, digest: false, history: false }, activity: [], isMemberPreview: true,
    onSaveProfile: vi.fn().mockReturnValue(true), onPreferenceChange: vi.fn(), onSavePreferences: vi.fn().mockReturnValue(true),
    onSaveSupportNote: vi.fn().mockReturnValue(true), onOpenActivity: vi.fn(), onOpenMembership: vi.fn() }
}
it('retains open edit drafts across new snapshots/rejection and discards them on cancel/reopen', () => {
  const input = props(); input.onSaveProfile.mockReturnValue(false)
  const view = render(<CommunityProfilePage {...input}/>)
  fireEvent.click(screen.getByRole('button', { name: 'Edit Profile' }))
  fireEvent.change(screen.getByLabelText('Your display name'), { target: { value: 'Draft' } })
  view.rerender(<CommunityProfilePage {...input} profile={{ ...input.profile, name: 'Refreshed' }} isMemberPreview={false}/>)
  expect((screen.getByLabelText('Your display name') as HTMLInputElement).value).toBe('Draft')
  fireEvent.submit(screen.getByRole('dialog').querySelector('form')!)
  expect(input.onSaveProfile).toHaveBeenCalledWith(expect.objectContaining({ name: 'Draft' }))
  expect(screen.getByRole('dialog')).toBeTruthy()
  expect(screen.getByLabelText('Your display name').getAttribute('maxlength')).toBe('40')
  expect(screen.getByLabelText('General location').getAttribute('maxlength')).toBe('60')
  expect(screen.getByLabelText('A little about you').getAttribute('maxlength')).toBe('300')
  fireEvent.click(screen.getByRole('button', { name: 'Close dialog' }))
  fireEvent.click(screen.getByRole('button', { name: 'Edit Profile' }))
  expect((screen.getByLabelText('Your display name') as HTMLInputElement).value).toBe('Refreshed')
  input.onSaveProfile.mockReturnValue(true)
  fireEvent.submit(screen.getByRole('dialog').querySelector('form')!)
  expect(screen.queryByRole('dialog')).toBeNull()
})
it('controls immediate preference actions and resets save feedback only on edits or leaving the view', () => {
  const input = props();const view = render(<CommunityProfilePage {...input}/>)
  fireEvent.click(screen.getByRole('button', { name: 'Membership & Settings' }))
  fireEvent.click(screen.getByRole('button', { name: 'Save preferences' }))
  expect(screen.getByRole('status').textContent).toContain('Saved for this visit')
  view.rerender(<CommunityProfilePage {...input} isMemberPreview={false}/>)
  expect(screen.getByRole('status')).toBeTruthy()
  fireEvent.click(screen.getByRole('switch', { name: /Share my activity history/ }))
  expect(input.onPreferenceChange).toHaveBeenCalledWith('history', true)
  expect(screen.queryByRole('status')).toBeNull()
  view.rerender(<CommunityProfilePage {...input} preferences={{ ...input.preferences, history: true }}/>)
  fireEvent.click(screen.getByRole('button', { name: 'Preview member-facing profile' }))
  expect(screen.getByRole('dialog').textContent).toContain(input.content.historyDisclosure)
  fireEvent.click(screen.getByRole('button', { name: 'Close dialog' }))
  fireEvent.click(screen.getByRole('button', { name: 'Save preferences' }))
  fireEvent.click(screen.getByRole('button', { name: 'Overview' }))
  fireEvent.click(screen.getByRole('button', { name: 'Membership & Settings' }))
  expect(screen.queryByRole('status')).toBeNull()
})
it('retains nested activity selection across main views and forwards activity/membership callbacks', () => {
  const input = props()
  render(<CommunityProfilePage {...input} activity={[{ id: 'table', title: 'Fictional table', art: 'azul', dateLabel: 'Oct 9', statusLabel: 'requested' }]}/>)
  fireEvent.click(screen.getByRole('button', { name: 'My Activity' }))
  fireEvent.click(screen.getByRole('button', { name: /Fictional table/ }))
  expect(input.onOpenActivity).toHaveBeenCalledWith('table')
  fireEvent.click(screen.getByRole('button', { name: 'History' }))
  fireEvent.click(screen.getByRole('button', { name: 'Overview' }))
  fireEvent.click(screen.getByRole('button', { name: 'My Activity' }))
  expect(screen.getByRole('button', { name: 'History' }).getAttribute('aria-pressed')).toBe('true')
  fireEvent.click(screen.getByRole('button', { name: /Crowded Table Member/ }))
  expect(input.onOpenMembership).toHaveBeenCalledOnce()
})
it('keeps rejected support drafts, clears them on reopening and closes only on success', () => {
  const input = props(); input.onSaveSupportNote.mockReturnValue(false)
  render(<CommunityProfilePage {...input}/>)
  fireEvent.click(screen.getByRole('button', { name: 'Membership & Settings' }))
  fireEvent.click(screen.getByRole('button', { name: /A question/ }))
  fireEvent.change(screen.getByLabelText('Your note'), { target: { value: '  Note  ' } })
  fireEvent.submit(screen.getByRole('dialog').querySelector('form')!)
  expect(input.onSaveSupportNote).toHaveBeenCalledWith('  Note  ')
  expect((screen.getByLabelText('Your note') as HTMLTextAreaElement).value).toBe('  Note  ')
  fireEvent.click(screen.getByRole('button', { name: 'Close dialog' }))
  fireEvent.click(screen.getByRole('button', { name: /A question/ }))
  expect((screen.getByLabelText('Your note') as HTMLTextAreaElement).value).toBe('')
  expect(screen.getByLabelText('Your note').getAttribute('maxlength')).toBe('2000')
  input.onSaveSupportNote.mockReturnValue(true)
  fireEvent.change(screen.getByLabelText('Your note'), { target: { value: 'Note' } })
  fireEvent.submit(within(screen.getByRole('dialog')).getByRole('button', { name: 'Save support note' }).closest('form')!)
  expect(screen.queryByRole('dialog')).toBeNull()
})
